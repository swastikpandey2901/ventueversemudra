// Helper to generate realistic historical price points over the last 3 years (~36 monthly points)
function generateThreeYearHistory(basePrice, volatility = 0.05) {
  const points = [];
  const now = Date.now();
  const ONE_MONTH = 30 * 24 * 60 * 60 * 1000;
  const TOTAL_MONTHS = 36;
  
  // Starting price 3 years ago (randomized around 60% to 110% of basePrice)
  let price = basePrice * (0.65 + Math.random() * 0.35);
  
  for (let i = TOTAL_MONTHS; i >= 0; i--) {
    const timestamp = now - (i * ONE_MONTH);
    if (i === 0) {
      price = basePrice;
    } else {
      // Market drift upwards with realistic fluctuation
      const drift = 0.008; // slight general market growth
      const changePercent = (Math.random() - 0.48) * volatility * 2 + drift;
      price = Math.max(1, price * (1 + changePercent));
    }
    points.push({
      price: parseFloat(price.toFixed(2)),
      timestamp: timestamp,
    });
  }
  return points;
}

