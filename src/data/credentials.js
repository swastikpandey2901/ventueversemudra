/**
 * Validates given input identifier & password.
 * Returns account info or null.
 */
export const verifyCredentials = (identifier, password) => {
  if (!identifier || !password) return null;
  const rawId = identifier.trim().toLowerCase();
  const rawPass = password.trim();

  // Check Admin
  if (ADMIN_CREDENTIALS[rawId]) {
    const admin = ADMIN_CREDENTIALS[rawId];
    if (admin.password === rawPass) {
      return {
        type: 'admin',
        username: admin.username,
        name: admin.name,
        email: `${admin.username}@mudra.internal`,
        password: admin.password,
        participantId: admin.username,
        role: 'admin',
        cash: admin.cash,
      };
    }
    return null;
  }

  // Check Participant (e.g. MUDRA001 or mudra001 or 001)
  let cleanId = rawId;
  if (/^\d{1,3}$/.test(cleanId)) {
    cleanId = 'mudra' + cleanId.padStart(3, '0');
  }

  if (PARTICIPANT_CREDENTIALS[cleanId]) {
    const part = PARTICIPANT_CREDENTIALS[cleanId];
    if (part.pass === rawPass) {
      return {
        type: 'student',
        username: part.id,
        name: `Trader ${part.id}`,
        email: `${cleanId}@mudra.internal`,
        password: part.pass,
        participantId: part.id,
        role: 'student',
        cash: 200000.0,
      };
    }
  }

  // Check Tester (e.g. TRIAL001 to TRIAL050 or trial001 or trial1)
  let cleanTrialId = rawId;
  const trialMatch = cleanTrialId.match(/^trial(\d{1,3})$/);
  if (trialMatch) {
    cleanTrialId = 'trial' + trialMatch[1].padStart(3, '0');
  }

  if (TESTER_CREDENTIALS[cleanTrialId]) {
    const tester = TESTER_CREDENTIALS[cleanTrialId];
    if (tester.pass === rawPass) {
      return {
        type: 'tester',
        username: tester.id,
        name: `Tester ${tester.id}`,
        email: `${cleanTrialId}@mudra.internal`,
        password: tester.pass,
        participantId: tester.id,
        role: 'student',
        cash: 200000.0,
      };
    }
  }

  return null;
};

/**
 * Checks if a participant ID belongs strictly to official tournament participants (MUDRA001 - MUDRA200)
 */
export const isOfficialParticipantId = (identifier) => {
  if (!identifier) return false;
  const match = String(identifier).trim().toUpperCase().match(/^MUDRA(\d{1,3})$/);
  if (!match) return false;
  const n = parseInt(match[1], 10);
  return n >= 1 && n <= 200;
};
